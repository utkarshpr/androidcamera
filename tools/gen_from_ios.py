"""Generates LookData.kt and PresetData.kt from the iPhone app's Swift sources (Looks.swift / CameraView.swift)."""
import re, sys
IOS = sys.argv[1]
OUT = sys.argv[2]
looks_src = open(f"{IOS}/Looks.swift").read()
view_src = open(f"{IOS}/CameraView.swift").read()

def split_top(s):
    parts, depth, cur, q = [], 0, "", False
    for ch in s:
        if ch == '"': q = not q
        if not q:
            if ch in "([": depth += 1
            if ch in ")]": depth -= 1
            if ch == "," and depth == 0:
                parts.append(cur.strip()); cur = ""; continue
        cur += ch
    if cur.strip(): parts.append(cur.strip())
    return parts

def balanced(src, start):  # src[start] == '(' → index of matching ')'
    depth, q = 0, False
    for i in range(start, len(src)):
        ch = src[i]
        if ch == '"': q = not q
        if q: continue
        if ch == '(': depth += 1
        if ch == ')':
            depth -= 1
            if depth == 0: return i
    raise ValueError

def num(s):
    s = s.strip()
    return eval(s.replace("Float", "").replace("Double", ""), {}, {})

# ---------------- looks
cases = re.findall(r'case (\w+) = "([^"]+)"', looks_src[looks_src.index("enum Look"):])
names = {c: n for c, n in cases}
specs = {}
for m in re.finditer(r'case \.(\w+): return LookSpec\(', looks_src):
    start = m.end() - 1
    end = balanced(looks_src, start)
    args = {}
    for part in split_top(looks_src[start + 1:end]):
        k, v = part.split(":", 1)
        args[k.strip()] = v.strip()
    specs[m.group(1)] = args

def triple(v):
    inner = v[v.index("(") + 1:v.rindex(")")]
    return [num(x) for x in inner.split(",")]

lk = ['package com.upravind.lumen', '', '// GENERATED by tools/gen_from_ios.py from the iPhone app. Do not edit by hand.', 'object LookData {', '    val specs: List<Pair<String, LookSpec>> = listOf(']
lk.append('        "ORIGINAL" to LookSpec(),')
for c, n in cases:
    if c in ("original", "custom") or c not in specs: continue
    a = specs[c]
    f = []
    for key in ("sat", "contrast", "brightness", "kelvin", "grain", "vignette", "halation", "sepia"):
        if key in a: f.append(f"{key} = {num(a[key])}f")
    if "fx" in a: f.append(f"fx = {int(num(a['fx']))}")
    for key in ("gain", "bias"):
        if key in a:
            t = triple(a[key]); f.append(f"{key} = floatArrayOf({t[0]}f, {t[1]}f, {t[2]}f)")
    if "swatch" in a:
        t = triple(a["swatch"]); f.append(f"swatch = 0xFF{int(t[0]*255):02X}{int(t[1]*255):02X}{int(t[2]*255):02X}")
    lk.append(f'        "{n}" to LookSpec({", ".join(f)}),')
lk += ['    )', '}']
open(f"{OUT}/LookData.kt", "w").write("\n".join(lk) + "\n")

# ---------------- presets
swift_look_to_name = {c: n for c, n in cases}
pr = ['package com.upravind.lumen', '', '// GENERATED by tools/gen_from_ios.py from the iPhone app. Do not edit by hand.', 'object PresetData {',
      '    val categories = listOf("FOOD", "PEOPLE", "INDOOR", "LANDSCAPE", "NIGHT", "STREET", "WEATHER", "CREATIVE", "PRO")', '    val all: List<Preset> = listOf(']
count = 0
for m in re.finditer(r'^\s*st\("', view_src, re.M):
    start = m.end() - 2
    end = balanced(view_src, start)
    parts = split_top(view_src[start + 1:end])
    cat = parts[0].strip('"'); name = parts[1].strip('"')
    look = swift_look_to_name[parts[2].lstrip(".")]; strength = num(parts[3])
    f = [f'cat = "{cat}"', f'name = "{name}"', f'look = "{look}"', f'strength = {strength}f']
    for p in parts[4:]:
        k, v = [x.strip() for x in p.split(":", 1)]
        if k == "manual":
            inner = v.strip()[1:-1]
            iso, sh = [x.split(":", 1)[1].strip() for x in split_top(inner)]
            f += [f"manualIso = {int(num(iso))}", f"manualShutter = {num(sh)}"]
        elif k in ("mode", "ratio"): f.append(f'{k} = {v}')
        elif k in ("grid", "leak", "dark"): f.append(f'{k} = {int(num(v))}')
        elif k in ("burst", "steady", "frame", "sky", "peaking", "zebra", "hist"):
            if k in ("peaking", "hist", "zebra"): continue
            f.append(f'{k} = {v}')
        elif k in ("grain", "glow", "dust", "bias"): f.append(f'{k} = {num(v)}f')
    pr.append(f'        Preset({", ".join(f)}),'); count += 1
pr += ['    )', '']
tips_block = view_src[view_src.index("let tips: [String: String] = ["):]
tips_block = tips_block[:tips_block.index("\n        ]")]
pr.append('    val tips: Map<String, String> = mapOf(')
for k, v in re.findall(r'"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"', tips_block):
    pr.append(f'        "{k.replace("$", chr(92) + "$")}" to "{v.replace("$", chr(92) + "$")}",')
pr += ['    )', '}']
open(f"{OUT}/PresetData.kt", "w").write("\n".join(pr) + "\n")
print("looks:", len(specs) + 1, "presets:", count)
